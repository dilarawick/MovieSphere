const poisoned = (u) => !u || POISONED.some((h) => String(u).includes(h));
export function applyPosterFix5(list) {
  return list.map((m) => {
    const c = CANON[m.title];
    if (c) return { ...m, poster: P(c[0]), backdrop: B(c[1]) };
    const out = { ...m };
    if (poisoned(out.poster)) out.poster = '';
    if (poisoned(out.backdrop)) out.backdrop = '';
    return out;
  });
}
